const formatRelativeTime = (dateStr?: string): string => {
  if (!dateStr) return '';
  const now = Date.now();
  const then = new Date(dateStr).getTime();
  if (isNaN(then)) return '';
  const diffSec = Math.floor((now - then) / 1000);
  if (diffSec < 60) return 'Justo ahora';
  const diffMin = Math.floor(diffSec / 60);
  if (diffMin < 60) return `hace ${diffMin}m`;
  const diffHrs = Math.floor(diffMin / 60);
  if (diffHrs < 24) return `hace ${diffHrs}h`;
  const diffDays = Math.floor(diffHrs / 24);
  return `hace ${diffDays}d`;
};

const parseTime12 = (timeStr?: string): { hour12: number; minute: number; isPM: boolean } => {
  if (!timeStr || !timeStr.includes(':')) {
    return { hour12: 8, minute: 0, isPM: true };
  }
  const [hStr, mStr] = timeStr.split(':');
  let h = parseInt(hStr, 10);
  let m = parseInt(mStr, 10);
  if (isNaN(h)) h = 20;
  if (isNaN(m)) m = 0;
  h = Math.max(0, Math.min(23, h));
  m = Math.max(0, Math.min(59, m));
  const isPM = h >= 12;
  const hour12 = h % 12 === 0 ? 12 : h % 12;
  return { hour12, minute: m, isPM };
};

const formatTime24 = (hour12: number, minute: number, isPM: boolean): string => {
  let h24 = hour12 % 12;
  if (isPM) h24 += 12;
  const hh = String(h24).padStart(2, '0');
  const mm = String(minute).padStart(2, '0');
  return `${hh}:${mm}`;
};

const formatDisplayTime12 = (timeStr?: string): string => {
  if (!timeStr || !timeStr.includes(':')) return '';
  const { hour12, minute, isPM } = parseTime12(timeStr);
  return `${String(hour12).padStart(2, '0')}:${String(minute).padStart(2, '0')} ${isPM ? 'PM' : 'AM'}`;
};

